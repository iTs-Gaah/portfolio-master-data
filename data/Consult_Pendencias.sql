    FROM CTT_CADASTRO_CENTRO_CUSTO
    WHERE CTT_BLOQ = '1'
       OR (TRIM(CTT_DTEXSF) <> '' AND STR_TO_DATE(CTT_DTEXSF, '%Y%m%d') < CURDATE())
) AS CTT

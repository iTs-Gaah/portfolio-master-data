SELECT
    'Pedido de Venda (SC6)' AS ORIGEM_DOC,
    SC6.C6_FILIAL AS FILIAL,
    SC6.C6_NUM AS NUMERO,
    MAX(SC6.C6_DATFAT) AS EMISSAO,
    SUM(SC6.C6_VALOR) AS TOTAL_DOC,
    CASE
        WHEN SUM(SC6.C6_QTDENT) > 0 THEN 'Atendido Parcialmente'
        ELSE 'Aberto'
    END AS SITUACAO,
    SC6.C6_CC AS CENTRO_CUSTO,
    CTT.CTT_DESC01 AS DESC_CC,
    CTT.CTT_BLOQ AS STATUS_BLOQ,
    CASE
        WHEN CTT.CTT_BLOQ = '1' THEN 'Bloqueado'
        ELSE 'Fim de Exercício'
    END AS MOTIVO_INATIVO
FROM (
    SELECT CTT_FILIAL, CTT_CUSTO, CTT_DESC01, CTT_BLOQ, CTT_DTEXSF
    FROM CTT_CADASTRO_CENTRO_CUSTO
    WHERE CTT_BLOQ = '1'
       OR (TRIM(CTT_DTEXSF) <> '' AND STR_TO_DATE(CTT_DTEXSF, '%Y%m%d') < CURDATE())
) AS CTT
INNER JOIN SC6_ITENS_PEDIDO_VENDA AS SC6
    ON SC6.C6_CC = CTT.CTT_CUSTO
   AND SC6.C6_FILIAL LIKE CONCAT(TRIM(CTT.CTT_FILIAL), '%')
WHERE SC6.C6_QTDENT < SC6.C6_QTDVEN
  AND SC6.C6_BLQ <> 'R'
GROUP BY
    SC6.C6_FILIAL, SC6.C6_NUM, SC6.C6_CC, CTT.CTT_DESC01, CTT.CTT_BLOQ, CTT.CTT_DTEXSF

UNION ALL


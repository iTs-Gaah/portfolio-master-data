    ON SD1.D1_CC = CTT.CTT_CUSTO
   AND SD1.D1_FILIAL LIKE CONCAT(TRIM(CTT.CTT_FILIAL), '%')
WHERE (SD1.D1_USRCLAS IS NULL OR TRIM(SD1.D1_USRCLAS) = '')
GROUP BY
    SD1.D1_FILIAL, SD1.D1_DOC, SD1.D1_CC, CTT.CTT_DESC01, CTT.CTT_BLOQ, CTT.CTT_DTEXSF
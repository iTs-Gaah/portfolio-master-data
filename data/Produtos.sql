SELECT DISTINCT
SB1.EMPRESA,
SB1.B1_COD,
SB1.B1_DESC,
SB1.B1_UM,
SB1.B1_TIPO,
SB1.B1_GRUPO,
SBM.BM_DESC,
SB1.B1_POSIPI,
SB1.B1_XCONTA,
SB1.B1_YCONTA,
SB1.B1_CODISS,
SB1.B1_XTPCUST,
SB1.B1_MSBLQL
FROM datalake_protheus_silver.sb1_cadastro_produto AS SB1
LEFT JOIN datalake_protheus_silver.sbm_cadastro_grupo_produto AS SBM ON SB1.B1_GRUPO = SBM.BM_GRUPO
WHERE LENGTH(TRIM(SB1.B1_COD)) = '10'
AND SB1.D_E_L_E_T_ <> '*'
AND SBM.D_E_L_E_T_ <> '*'
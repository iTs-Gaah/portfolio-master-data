
WITH EMPRESA_X_PROD AS (
    SELECT B1_COD, B1_DESC, B1_MSBLQL, R_E_C_N_O_, S_T_A_M_P_
    FROM "datalake_protheus_silver"."sb1_cadastro_produto"
    WHERE EMPRESA = 'EMPRESA_01'
  	AND D_E_L_E_T_ <> '*'
),
PROJETO_ALFA_PROD AS (
    SELECT B1_COD, B1_DESC, B1_MSBLQL, R_E_C_N_O_, S_T_A_M_P_
    FROM "datalake_protheus_silver"."sb1_cadastro_produto"
    WHERE EMPRESA = 'CONSORCIO PROJETO_ALFA'
  	AND D_E_L_E_T_ <> '*'
),
EMPRESA_X_FORN AS (
    SELECT A2_COD, A2_LOJA, A2_NOME, A2_CGC, A2_MSBLQL, R_E_C_N_O_, S_T_A_M_P_
    FROM "datalake_protheus_silver"."sa2_cadastro_fornecedor"
    WHERE EMPRESA = 'EMPRESA_01
  	AND D_E_L_E_T_ <> '*'
),
PROJETO_ALFA_FORN AS (
    SELECT A2_COD, A2_LOJA, A2_NOME, A2_CGC, A2_MSBLQL, R_E_C_N_O_, S_T_A_M_P_
    FROM "datalake_protheus_silver"."sa2_cadastro_fornecedor"
    WHERE EMPRESA = 'CONSORCIO PROJETO_ALFA'
  	AND D_E_L_E_T_ <> '*'
),
EMPRESA_X_CLI AS (
    SELECT A1_COD, A1_LOJA, A1_NOME, A1_CGC, A1_MSBLQL, R_E_C_N_O_, S_T_A_M_P_
    FROM "datalake_protheus_silver"."sa1_cadastro_cliente"
    WHERE EMPRESA = 'EMPRESA_01'
  	AND D_E_L_E_T_ <> '*'
),
PROJETO_ALFA_CLI AS (
    SELECT A1_COD, A1_LOJA, A1_NOME, A1_CGC, A1_MSBLQL, R_E_C_N_O_, S_T_A_M_P_
    FROM "datalake_protheus_silver"."sa1_cadastro_cliente"
    WHERE EMPRESA = 'CONSORCIO PROJETO_ALFA'
  	AND D_E_L_E_T_ <> '*'
),
RESULTADO_FINAL AS (

    SELECT 
        'PRODUTO' AS TIPO,
        C.B1_COD AS COD_EMPRESA_X, 
        '' AS LOJA_EMPRESA_X, 
        LTRIM(RTRIM(C.B1_DESC)) AS DESC_EMPRESA_X, 
        CASE WHEN C.B1_MSBLQL = '2' THEN 'ATIVO' ELSE 'INATIVO' END AS STATUS_EMPRESA_X,
        C.R_E_C_N_O_ AS RECNO_EMPRESA_X,
        C.S_T_A_M_P_ AS STAMP_EMPRESA_X,
        ' | ' AS SEP,
        R.B1_COD AS COD_PROJETO_ALFA, 
        '' AS LOJA_PROJETO_ALFA,
        LTRIM(RTRIM(R.B1_DESC)) AS DESC_PROJETO_ALFA,
        CASE WHEN R.B1_MSBLQL = '2' THEN 'ATIVO' ELSE 'INATIVO' END AS STATUS_PROJETO_ALFA,
        R.R_E_C_N_O_ AS RECNO_PROJETO_ALFA,
        R.S_T_A_M_P_ AS STAMP_PROJETO_ALFA,
        CASE 
            WHEN C.B1_COD IS NULL OR R.B1_COD IS NULL THEN 'Produto não cadastrado'
            WHEN LTRIM(RTRIM(C.B1_DESC)) <> LTRIM(RTRIM(R.B1_DESC)) THEN 'Descrição divergente para mesmo código'
            ELSE 'Cadastros iguais'
        END AS VALIDACAO
    FROM EMPRESA_X_PROD C
    LEFT JOIN PROJETO_ALFA_PROD R ON C.B1_COD = R.B1_COD

    UNION ALL

    SELECT 
        'PRODUTO' AS TIPO,
        C.B1_COD AS COD_EMPRESA_X, 
        '' AS LOJA_EMPRESA_X, 
        LTRIM(RTRIM(C.B1_DESC)) AS DESC_EMPRESA_X, 
        CASE WHEN C.B1_MSBLQL = '2' THEN 'ATIVO' ELSE 'INATIVO' END AS STATUS_EMPRESA_X,
        C.R_E_C_N_O_ AS RECNO_EMPRESA_X,
        C.S_T_A_M_P_ AS STAMP_EMPRESA_X,
        ' | ' AS SEP,
        R.B1_COD AS COD_PROJETO_ALFA, 
        '' AS LOJA_PROJETO_ALFA,
        LTRIM(RTRIM(R.B1_DESC)) AS DESC_PROJETO_ALFA,
        CASE WHEN R.B1_MSBLQL = '2' THEN 'ATIVO' ELSE 'INATIVO' END AS STATUS_PROJETO_ALFA,
        R.R_E_C_N_O_ AS RECNO_PROJETO_ALFA,
        R.S_T_A_M_P_ AS STAMP_PROJETO_ALFA,
        CASE 
            WHEN C.B1_COD IS NULL OR R.B1_COD IS NULL THEN 'Produto não cadastrado'
            WHEN LTRIM(RTRIM(C.B1_DESC)) <> LTRIM(RTRIM(R.B1_DESC)) THEN 'Descrição divergente para mesmo código'
            ELSE 'Cadastros iguais'
        END AS VALIDACAO
    FROM EMPRESA_X_PROD C
    RIGHT JOIN PROJETO_ALFA_PROD R ON C.B1_COD = R.B1_COD
    WHERE C.B1_COD IS NULL

    UNION ALL

    SELECT 
        'FORNECEDOR' AS TIPO,
        C.A2_COD AS COD_EMPRESA_X, 
        C.A2_LOJA AS LOJA_EMPRESA_X, 
        LTRIM(RTRIM(C.A2_NOME)) AS DESC_EMPRESA_X, 
        CASE WHEN C.A2_MSBLQL = '2' THEN 'ATIVO' ELSE 'INATIVO' END AS STATUS_EMPRESA_X, 
        C.R_E_C_N_O_ AS RECNO_EMPRESA_X,
        C.S_T_A_M_P_ AS STAMP_EMPRESA_X,
        ' | ' AS SEP,
        R.A2_COD AS COD_PROJETO_ALFA, 
        R.A2_LOJA AS LOJA_PROJETO_ALFA, 
        LTRIM(RTRIM(R.A2_NOME)) AS DESC_PROJETO_ALFA, 
        CASE WHEN R.A2_MSBLQL = '2' THEN 'ATIVO' ELSE 'INATIVO' END AS STATUS_PROJETO_ALFA, 
        R.R_E_C_N_O_ AS RECNO_PROJETO_ALFA,
        R.S_T_A_M_P_ AS STAMP_PROJETO_ALFA,
        CASE 
            WHEN C.A2_COD IS NULL OR R.A2_COD IS NULL THEN 'Fornecedor não cadastrado'
            WHEN LTRIM(RTRIM(C.A2_CGC)) <> LTRIM(RTRIM(R.A2_CGC)) THEN 'CNPJ divergente para mesmo código'
            WHEN LTRIM(RTRIM(C.A2_NOME)) <> LTRIM(RTRIM(R.A2_NOME)) THEN 'Valores são diferentes entre as bases'
            ELSE 'Cadastros iguais'
        END AS VALIDACAO
    FROM EMPRESA_X_FORN C
    LEFT JOIN PROJETO_ALFA_FORN R 
        ON C.A2_COD = R.A2_COD 
       AND C.A2_LOJA = R.A2_LOJA

    UNION ALL

    SELECT 
        'FORNECEDOR' AS TIPO,
        C.A2_COD AS COD_EMPRESA_X, 
        C.A2_LOJA AS LOJA_EMPRESA_X, 
        LTRIM(RTRIM(C.A2_NOME)) AS DESC_EMPRESA_X, 
        CASE WHEN C.A2_MSBLQL = '2' THEN 'ATIVO' ELSE 'INATIVO' END AS STATUS_EMPRESA_X, 
        C.R_E_C_N_O_ AS RECNO_EMPRESA_X,
        C.S_T_A_M_P_ AS STAMP_EMPRESA_X,
        ' | ' AS SEP,
        R.A2_COD AS COD_PROJETO_ALFA, 
        R.A2_LOJA AS LOJA_PROJETO_ALFA, 
        LTRIM(RTRIM(R.A2_NOME)) AS DESC_PROJETO_ALFA, 
        CASE WHEN R.A2_MSBLQL = '2' THEN 'ATIVO' ELSE 'INATIVO' END AS STATUS_PROJETO_ALFA, 
        R.R_E_C_N_O_ AS RECNO_PROJETO_ALFA,
        R.S_T_A_M_P_ AS STAMP_PROJETO_ALFA,
        CASE 
            WHEN C.A2_COD IS NULL OR R.A2_COD IS NULL THEN 'Fornecedor não cadastrado'
            WHEN LTRIM(RTRIM(C.A2_CGC)) <> LTRIM(RTRIM(R.A2_CGC)) THEN 'CNPJ divergente para mesmo código'
            WHEN LTRIM(RTRIM(C.A2_NOME)) <> LTRIM(RTRIM(R.A2_NOME)) THEN 'Valores são diferentes entre as bases'
            ELSE 'Cadastros iguais'
        END AS VALIDACAO
    FROM EMPRESA_X_FORN C
    RIGHT JOIN PROJETO_ALFA_FORN R 
        ON C.A2_COD = R.A2_COD 
       AND C.A2_LOJA = R.A2_LOJA
    WHERE C.A2_COD IS NULL

    UNION ALL

    SELECT 
        'CLIENTE' AS TIPO,
        C.A1_COD AS COD_EMPRESA_X, 
        C.A1_LOJA AS LOJA_EMPRESA_X, 
        LTRIM(RTRIM(C.A1_NOME)) AS DESC_EMPRESA_X, 
        CASE WHEN C.A1_MSBLQL = '2' THEN 'ATIVO' ELSE 'INATIVO' END AS STATUS_EMPRESA_X, 
        C.R_E_C_N_O_ AS RECNO_EMPRESA_X,
        C.S_T_A_M_P_ AS STAMP_EMPRESA_X,
        ' | ' AS SEP,
        R.A1_COD AS COD_PROJETO_ALFA, 
        R.A1_LOJA AS LOJA_PROJETO_ALFA, 
        LTRIM(RTRIM(R.A1_NOME)) AS DESC_PROJETO_ALFA, 
        CASE WHEN R.A1_MSBLQL = '2' THEN 'ATIVO' ELSE 'INATIVO' END AS STATUS_PROJETO_ALFA, 
        R.R_E_C_N_O_ AS RECNO_PROJETO_ALFA,
        R.S_T_A_M_P_ AS STAMP_PROJETO_ALFA,
        CASE 
            WHEN C.A1_COD IS NULL OR R.A1_COD IS NULL THEN 'Cliente não cadastrado'
            WHEN LTRIM(RTRIM(C.A1_CGC)) <> LTRIM(RTRIM(R.A1_CGC)) THEN 'CNPJ divergente para mesmo código'
            WHEN LTRIM(RTRIM(C.A1_NOME)) <> LTRIM(RTRIM(R.A1_NOME)) THEN 'Valores são diferentes entre as bases'
            ELSE 'Cadastros iguais'
        END AS VALIDACAO
    FROM EMPRESA_X_CLI C
    LEFT JOIN PROJETO_ALFA_CLI R 
        ON C.A1_COD = R.A1_COD 
       AND C.A1_LOJA = R.A1_LOJA

    UNION ALL

    SELECT 
        'CLIENTE' AS TIPO,
        C.A1_COD AS COD_EMPRESA_X, 
        C.A1_LOJA AS LOJA_EMPRESA_X, 
        LTRIM(RTRIM(C.A1_NOME)) AS DESC_EMPRESA_X, 
        CASE WHEN C.A1_MSBLQL = '2' THEN 'ATIVO' ELSE 'INATIVO' END AS STATUS_EMPRESA_X, 
        C.R_E_C_N_O_ AS RECNO_EMPRESA_X,
        C.S_T_A_M_P_ AS STAMP_EMPRESA_X,
        ' | ' AS SEP,
        R.A1_COD AS COD_PROJETO_ALFA, 
        R.A1_LOJA AS LOJA_PROJETO_ALFA, 
        LTRIM(RTRIM(R.A1_NOME)) AS DESC_PROJETO_ALFA, 
        CASE WHEN R.A1_MSBLQL = '2' THEN 'ATIVO' ELSE 'INATIVO' END AS STATUS_PROJETO_ALFA, 
        R.R_E_C_N_O_ AS RECNO_PROJETO_ALFA,
        R.S_T_A_M_P_ AS STAMP_PROJETO_ALFA,
        CASE 
            WHEN C.A1_COD IS NULL OR R.A1_COD IS NULL THEN 'Cliente não cadastrado'
            WHEN LTRIM(RTRIM(C.A1_CGC)) <> LTRIM(RTRIM(R.A1_CGC)) THEN 'CNPJ divergente para mesmo código'
            WHEN LTRIM(RTRIM(C.A1_NOME)) <> LTRIM(RTRIM(R.A1_NOME)) THEN 'Valores são diferentes entre as bases'
            ELSE 'Cadastros iguais'
        END AS VALIDACAO
    FROM EMPRESA_X_CLI C
    RIGHT JOIN PROJETO_ALFA_CLI R 
        ON C.A1_COD = R.A1_COD 
       AND C.A1_LOJA = R.A1_LOJA
    WHERE C.A1_COD IS NULL
)
SELECT TIPO, COD_EMPRESA_X, LOJA_EMPRESA_X, DESC_EMPRESA_X, STATUS_EMPRESA_X, RECNO_EMPRESA_X, STAMP_EMPRESA_X, SEP, COD_PROJETO_ALFA, LOJA_PROJETO_ALFA, DESC_PROJETO_ALFA, STATUS_PROJETO_ALFA, RECNO_PROJETO_ALFA, STAMP_PROJETO_ALFA, VALIDACAO
FROM (
    SELECT *, COALESCE(RECNO_EMPRESA_X, RECNO_PROJETO_ALFA) AS ORDENACAO
    FROM RESULTADO_FINAL
) AS RESULTADO_ORDENADO
ORDER BY 
    TIPO DESC, 
    ORDENACAO ASC
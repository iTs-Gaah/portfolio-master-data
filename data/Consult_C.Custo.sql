SELECT
    CTT_EMPRESA,
    CASE 
        WHEN EMPRESA IN ('CONSORCIO_K', '03') AND TRIM(CTT_CUSTO) = 'CC_01' THEN 'FILIAL_06'
        WHEN TRIM(CTT_FILIAL) = '01' THEN 'FILIAL_05'
        WHEN TRIM(CTT_FILIAL) = '02' THEN 'FILIAL_07'
        WHEN TRIM(CTT_FILIAL) = '03' THEN 'FILIAL_08'
        WHEN TRIM(CTT_FILIAL) = '04' THEN 'FILIAL_10'
        WHEN TRIM(CTT_FILIAL) = '05' THEN 'FILIAL_11'
        WHEN TRIM(CTT_FILIAL) = '06' THEN 'FILIAL_12'
        WHEN TRIM(CTT_FILIAL) = '07' THEN 'FILIAL_13'
        WHEN TRIM(CTT_FILIAL) = '08' THEN 'FILIAL_14'
        WHEN TRIM(CTT_FILIAL) = '09' THEN 'FILIAL_15'
        WHEN TRIM(CTT_FILIAL) = '10' THEN 'FILIAL_16'
        WHEN TRIM(CTT_FILIAL) = '11' THEN 'FILIAL_17'
        WHEN TRIM(CTT_FILIAL) = '12' THEN 'FILIAL_18'
        WHEN TRIM(CTT_FILIAL) = '13' THEN 'FILIAL_19'
        WHEN TRIM(CTT_FILIAL) = '14' THEN 'FILIAL_20'
        WHEN TRIM(CTT_FILIAL) = '15' THEN 'FILIAL_21'
        WHEN TRIM(CTT_FILIAL) = '16' THEN 'FILIAL_22'
        ELSE CTT_FILIAL
    END AS CTT_FILIAL,
    CTT_CUSTO,
    CTT_DESC01,
    CASE
        WHEN CTT_BLOQ = '2' THEN 'ATIVO' 
        ELSE 'INATIVO' 
    END AS CTT_BLOQ,
    CTT_XFINAN,
    CTT_REGION,
    CTT_DTEXIS,
    CTT_DTEXSF
FROM datalake_protheus_silver.ctt_cadastro_centro_custo
WHERE LENGTH(TRIM(CTT_CUSTO)) = 8
AND D_E_L_E_T_ <> '*'